"""Generate docs/traceability.md: every defined ID and the tests that cite it.

    uv run python scripts/trace_matrix.py            write the matrix
    uv run python scripts/trace_matrix.py --check    exit 1 if it is stale; write nothing
    uv run python scripts/trace_matrix.py --stdout   print it instead of writing

The matrix is never edited by hand. A test runs --check, so a stale one fails the suite.
"""

import argparse
import json
import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from tests.guards.spec_ids import defined_ids  # noqa: E402

MATRIX = REPO / "docs" / "traceability.md"
REGENERATE = "uv run python scripts/trace_matrix.py"

KINDS = [
    ("AC", "Acceptance criteria"),
    ("FR", "Functional requirements"),
    ("NFR", "Non-functional requirements"),
    ("EC", "Edge cases"),
    ("V", "Validation refusals"),
    ("W", "Validation warnings"),
    ("CONST", "Constitution guard rails"),
]
ROMAN = ["I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X", "SECRETS"]


def collect() -> dict[str, list[str]]:
    """Collect the suite without running it; return test function → cited IDs."""
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        result = subprocess.run(
            [
                sys.executable,
                "-m",
                "pytest",
                "--collect-only",
                "-q",
                "-p",
                "no:cacheprovider",
                f"--trace-report={report}",
            ],
            cwd=REPO,
            capture_output=True,
            text=True,
        )
        if result.returncode != 0:
            sys.exit(f"test collection failed:\n{result.stdout}{result.stderr}")
        return json.loads(report.read_text())


def order(test_id: str) -> tuple:
    kind, _, rest = test_id.partition("-")
    return (rest.isdigit(), int(rest) if rest.isdigit() else ROMAN.index(rest))


def render(ids: dict[str, str], report: dict[str, list[str]]) -> str:
    tests_for = defaultdict(list)
    for test, cited in report.items():
        for i in cited:
            tests_for[i].append(test)

    lines = [
        "# Traceability matrix",
        "",
        f"Generated by `scripts/trace_matrix.py` — do not edit by hand. Regenerate with "
        f"`{REGENERATE}`.",
        "Each row is an ID defined in the specification, with the tests that cite it. "
        "`—` means no test yet.",
        "",
        "| Kind | Defined | Covered |",
        "|---|---:|---:|",
    ]
    by_kind = {k: sorted((i for i in ids if i.split("-")[0] == k), key=order) for k, _ in KINDS}
    for kind, title in KINDS:
        covered = sum(1 for i in by_kind[kind] if tests_for[i])
        lines.append(f"| {title} ({kind}) | {len(by_kind[kind])} | {covered} |")

    for kind, title in KINDS:
        if not by_kind[kind]:
            continue
        source = ids[by_kind[kind][0]]
        lines += ["", f"## {title} — `{source}`", "", "| ID | Tests |", "|---|---|"]
        for i in by_kind[kind]:
            cell = "<br>".join(f"`{t}`" for t in sorted(tests_for[i])) or "—"
            lines.append(f"| {i} | {cell} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="exit 1 if the matrix is stale")
    mode.add_argument("--stdout", action="store_true", help="print instead of writing")
    args = parser.parse_args()

    text = render(defined_ids(REPO), collect())
    if args.stdout:
        sys.stdout.write(text)
    elif args.check:
        if not MATRIX.exists() or MATRIX.read_text() != text:
            print(f"docs/traceability.md is stale — run: {REGENERATE}")
            return 1
    else:
        MATRIX.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
